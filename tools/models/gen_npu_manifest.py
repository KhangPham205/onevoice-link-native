#!/usr/bin/env python3
"""Regenerate android-app/app/src/main/assets/npu_manifest.json.

The graph name inside a QNN context binary is generated by Qualcomm AI Hub
(`graph_08xlh5ri`, `opus_mt_encoder`, …) and is NOT recorded in the metadata.json
that ships beside it. `graphRetrieve` fails on any mismatch, so the only safe
source is the binary itself — HANDOFF.md §7-B2 says the same.

This reads every deploy .bin with the SDK's qnn-context-binary-utility, extracts
graph identity plus the full I/O contract, and writes the asset the app parses.

Run it on a Linux x86_64 box with the QAIRT SDK vendored under
native-core/third_party/qnn_sdk (the tool does not run on the phone):

    python3 tools/models/gen_npu_manifest.py

The tool links against libc++; if your distro has no libc++.so.1, point
LIBCXX_DIR at any directory containing one.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SDK = os.path.join(REPO, "native-core", "third_party", "qnn_sdk")
BINS = os.path.join(REPO, "onevoice-npu-bins")
DEST = os.path.join(REPO, "android-app", "app", "src", "main", "assets",
                    "npu_manifest.json")
TOOL = os.path.join(SDK, "bin", "x86_64-linux-clang", "qnn-context-binary-utility")

# Snapdragon 8 Gen 2 == SM8550 == QNN_SOC_MODEL_SM8550 (43), Hexagon v73.
TARGET_SOC = {"qnnSocModel": 43, "socModel": "SM8550",
              "marketing": "Snapdragon 8 Gen 2", "hexagon": "v73"}

# (direction, stage, deployed filename, path under onevoice-npu-bins/)
# Chosen per HANDOFF.md §4 "keepers": Parakeet for ASR, opus-mt for MT (clean
# licence, ~4.6x lighter than NLLB), Kokoro for TTS in the target language.
DEPLOY = [
    ("vi-en", "asr",         "asr_parakeet_vi.bin", "asr/parakeet_ctc_vi__DEPLOY/logits.bin"),
    ("vi-en", "mt_encoder",  "mt_encoder.bin",      "mt/opus_mt_vi_en__float_8gen2/encoder_float.bin"),
    ("vi-en", "mt_decoder",  "mt_decoder.bin",      "mt/opus_mt_vi_en__float_8gen2/decoder_float.bin"),
    ("vi-en", "tts_encoder", "tts_encoder.bin",     "tts/kokoro_en__encoder_8gen2/encoder.bin"),
    ("vi-en", "tts_decoder", "tts_decoder.bin",     "tts/kokoro_en__decoder_npu_8gen2/decoder_npu.bin"),
    # No ASR row: the package ships Vietnamese ASR only (HANDOFF.md §4), so
    # EN->VI is marked unavailable below and the app locks the toggle.
    ("en-vi", "mt_encoder",  "mt_encoder.bin",      "mt/opus_mt_en_vi__float_8gen2/encoder_float.bin"),
    ("en-vi", "mt_decoder",  "mt_decoder.bin",      "mt/opus_mt_en_vi__float_8gen2/decoder_float.bin"),
    ("en-vi", "tts_encoder", "tts_encoder.bin",     "tts/kokoro_vi__encoder_8gen2/encoder.bin"),
    ("en-vi", "tts_decoder", "tts_decoder.bin",     "tts/kokoro_vi__decoder_npu_8gen2/decoder_npu.bin"),
]

LABELS = {
    "asr": "ASR · Parakeet-CTC vi",
    "mt_encoder": "MT encoder · opus-mt",
    "mt_decoder": "MT decoder · opus-mt",
    "tts_encoder": "TTS encoder · Kokoro",
    "tts_decoder": "TTS decoder · Kokoro",
}


def ld_path() -> str:
    parts = [os.path.join(SDK, "lib", "x86_64-linux-clang")]
    if os.environ.get("LIBCXX_DIR"):
        parts.insert(0, os.environ["LIBCXX_DIR"])
    if os.environ.get("LD_LIBRARY_PATH"):
        parts.append(os.environ["LD_LIBRARY_PATH"])
    return ":".join(parts)


def dump(src: str) -> dict:
    """Run qnn-context-binary-utility and return its parsed JSON."""
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
        out = tmp.name
    try:
        env = dict(os.environ, LD_LIBRARY_PATH=ld_path())
        proc = subprocess.run([TOOL, "--context_binary", src, "--json_file", out],
                              env=env, capture_output=True, text=True)
        if not os.path.exists(out) or os.path.getsize(out) == 0:
            raise RuntimeError(
                f"{TOOL} produced nothing for {src}\n{proc.stdout}\n{proc.stderr}")
        with open(out) as f:
            return json.load(f)
    finally:
        if os.path.exists(out):
            os.unlink(out)


def tensor(t: dict) -> dict:
    i = t["info"]
    return {"name": i["name"],
            "dtype": i["dataType"].replace("QNN_DATATYPE_", ""),
            "dims": i["dimensions"]}


def main() -> int:
    if not os.path.isfile(TOOL):
        print(f"!! missing {TOOL} — vendor the QAIRT SDK first", file=sys.stderr)
        return 1

    by_direction: dict[str, list] = {}
    for direction, stage, dest_name, rel in DEPLOY:
        src = os.path.join(BINS, rel)
        if not os.path.isfile(src):
            print(f"!! missing source {rel}", file=sys.stderr)
            return 1
        info = dump(src)["info"]
        graph = info["graphs"][0]["info"]
        soc = info.get("socModel")
        if soc != TARGET_SOC["qnnSocModel"]:
            print(f"!! {rel}: socModel={soc}, expected "
                  f"{TARGET_SOC['qnnSocModel']} — wrong chip, refusing to write",
                  file=sys.stderr)
            return 1
        by_direction.setdefault(direction, []).append({
            "stage": stage,
            "label": LABELS[stage],
            "file": f"{direction}/{dest_name}",
            "graph": graph["graphName"],
            "sizeBytes": os.path.getsize(src),
            "inputs": [tensor(t) for t in graph["graphInputs"]],
            "outputs": [tensor(t) for t in graph["graphOutputs"]],
        })
        print(f"{direction:6s} {stage:12s} graph={graph['graphName']:18s} "
              f"{os.path.getsize(src)/1048576:7.1f} MB  build={info['buildId']}")

    manifest = {
        "schemaVersion": 1,
        "comment": "Generated by tools/models/gen_npu_manifest.py from the "
                   "context binaries themselves (HANDOFF.md §7-B2). Graph names "
                   "are AI Hub-generated; graphRetrieve fails on any mismatch.",
        "targetSoc": TARGET_SOC,
        "modelRoot": "models/npu",
        "directions": [
            {"id": "vi-en", "label": "VI → EN", "available": True,
             "unavailableReason": None, "stages": by_direction.get("vi-en", [])},
            {"id": "en-vi", "label": "EN → VI", "available": False,
             "unavailableReason": "missing_asr_en",
             "stages": by_direction.get("en-vi", [])},
        ],
    }
    os.makedirs(os.path.dirname(DEST), exist_ok=True)
    with open(DEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nwrote {DEST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
